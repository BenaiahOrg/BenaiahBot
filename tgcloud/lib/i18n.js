const strings = { en, am };

export function normalizeLang(lang) {
  return lang === 'am' ? 'am' : 'en';
}

// t('am', 'offer', 12, 'English') → the Amharic offer text.
export function t(lang, key, ...params) {
  const value = strings[normalizeLang(lang)][key] ?? en[key];
  if (value == null) return key;
  return typeof value === 'function' ? value(...params) : value;
}

// All translations of one key, for matching reply-keyboard button presses.
export function allTranslations(key) {
  return Object.values(strings).map((table) => table[key]).filter((value) => typeof value === 'string');
}
